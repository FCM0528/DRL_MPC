function code=native_function_script(mode)
% Pure MATLAB algorithms: no extrinsic calls, workspace eval or hidden MEX.
switch mode
case 'errors'
code=sprintf('function e=fcn(s,r)\ne=[s(2)-r(1);atan2(sin(s(5)-r(2)),cos(s(5)-r(2)))];\nend');
case 'observation'
code=sprintf(['function o=fcn(s,r)\n' ...
'ey=s(2)-r(1);ep=atan2(sin(s(5)-r(2)),cos(s(5)-r(2)));\n' ...
'xd=s(3)*cos(s(5))-s(4)*sin(s(5));yd=s(3)*sin(s(5))+s(4)*cos(s(5));\n' ...
'o=max(-1,min(1,[ey;ep;yd-r(4)*xd;s(6)-xd*r(3);s(3);r(3)]./[.25;.1;2;.5;30;.05]));\nend']);
case 'action'
code=sprintf(['function [p,lambda]=fcn(a,mode)\n' ...
'y=[25 55 85 115 155 200 240];h=[100 300 500 700 900 1000 1100 1300];l=[-1 -.7 -.5 -.3 0 .3 .5 1];\n' ...
'a=max(-1,min(1,a));lambda=l(1+round((a(3)+1)*3.5));\n' ...
'p=[40;80*y(1+round((a(1)+1)*3));4*h(1+round((a(2)+1)*3.5));13500;lambda];\n' ...
'if mode==2,lambda=0;p(5)=0;end\n' ...
'if mode==0,p=[40;9200;2800;13500;0];lambda=0;end\nend']);
case 'reward'
code=sprintf(['function [reward,done]=fcn(s,d,a,r,t)\n' ...
'ey=s(2)-r(1);ep=atan2(sin(s(5)-r(2)),cos(s(5)-r(2)));\n' ...
'reward=-300*abs(ey)/.25-50*abs(ep)/.1-60*d(1)^2-15*a(1)^2-15*a(2)^2-20*a(3)^2;\n' ...
'failed=any(~isfinite(s))||abs(ey)>1.5||abs(s(11))>8*pi/180;\n' ...
'done=double(failed||s(1)>=120||t>=19.999);if failed,reward=reward-100;end\nend']);
end
end
